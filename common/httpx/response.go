package httpx

import (
	"io"
	"net/http"
)

// DrainAndClose drains and closes the response body to avoid connection/resource leaks. It is safe to call with a nil
// response or body, which is what http.Client.Do returns together with a transport error.
func DrainAndClose(resp *http.Response) {
	if resp == nil || resp.Body == nil {
		return
	}
	_, _ = io.Copy(io.Discard, resp.Body)
	_ = resp.Body.Close()
}
